#!/usr/bin/env python3
"""Writes syscall-groups.inc, the table of the syscall groups (@system-service,
@privileged, …) that unit-seccomp.c reads, out of systemd's
src/shared/seccomp-util.c.

    gen-syscall-groups.py SYSTEMD-SOURCE/src/shared/seccomp-util.c > syscall-groups.inc

The table is checked in; run this again (against the systemd of nixpkgs) when
the groups should follow a newer one.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("const SyscallFilterSet syscall_filter_sets[")
body = src[start:]
body = body[: body.index("\n};")]

groups = []
for m in re.finditer(r'\.name = "(@[a-z-]+)",.*?\.value =(.*?)\n        \},', body, re.S):
    name, value = m.group(1), m.group(2)
    if name == "@known":
        continue        # everything there is: unit-seccomp builds it
    value = re.sub(r"/\*.*?\*/", "", value, flags=re.S)
    members = re.findall(r'"([^"]*?)\\0"', value)
    groups.append((name, members))

print("/* generated by gen-syscall-groups.py from systemd's seccomp-util.c; do not edit */")
for name, members in groups:
    print('{ "%s",' % name)
    line = ""
    for mem in members:
        piece = '"%s\\0"' % mem
        if len(line) + len(piece) > 70:
            print("  " + line)
            line = ""
        line += (" " if line else "") + piece
    if line:
        print("  " + line)
    print("},")
